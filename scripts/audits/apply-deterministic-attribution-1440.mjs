import fs from "node:fs";
const path = "scripts/audits/unified-listing-card-1-visual.mjs";
let source = fs.readFileSync(path, "utf8");
const before = '  { name: "desktop-1280x900", width: 1280, height: 900 },\n];';
const after = '  { name: "desktop-1280x900", width: 1280, height: 900 },\n  { name: "desktop-1440x900", width: 1440, height: 900 },\n];';
const count = source.split(before).length - 1;
if (count !== 1) throw new Error(`${path}: expected viewport marker once, got ${count}`);
source = source.replace(before, after);
fs.writeFileSync(path, source, "utf8");
console.log("DETERMINISTIC-ATTRIBUTION-1 1440 viewport PASS");
