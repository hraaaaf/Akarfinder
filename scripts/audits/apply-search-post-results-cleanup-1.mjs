import fs from 'node:fs';
const path = 'components/search/LightZillowSearchShell.tsx';
let s = fs.readFileSync(path, 'utf8');
const oldToken = '${view === "split" ? "lg:hidden" : ""}';
const newToken = '${view === "split" ? "hidden" : ""}';
const count = s.split(oldToken).length - 1;
if (count !== 2) throw new Error(`Expected exactly 2 split secondary markers, found ${count}`);
s = s.split(oldToken).join(newToken);
fs.writeFileSync(path, s);
console.log('SEARCH-POST-RESULTS-CLEANUP-1 shell patch applied');
